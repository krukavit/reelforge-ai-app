#!/data/data/com.termux/files/usr/bin/bash
set -eu

SCRIPT_DIR="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
TARGET="${AGENT_NEXT_TARGET:-$HOME/reelforge-agent-next}"
MODE="refuse"

case "${1:-}" in
  "") ;;
  --replace) MODE="replace" ;;
  -h|--help)
    cat <<'EOF'
Usage: ./INSTALL.sh [--replace]

Installs this Agent Next source snapshot into ~/reelforge-agent-next.
Default: refuse to overwrite an existing target.
--replace: create a timestamped HOME backup, then replace Agent Next
source/config/tests/registry while preserving the existing shared ops stack
and existing runtime StateStore files.

This installer never copies credentials and never modifies production.
EOF
    exit 0
    ;;
  *)
    echo "Unknown option: $1" >&2
    exit 2
    ;;
esac

if [ "$SCRIPT_DIR" = "$TARGET" ]; then
  echo "REFUSING_SELF_INSTALL: extract the archive outside the target first" >&2
  exit 1
fi

if [ -e "$TARGET" ]; then
  if [ "$MODE" != "replace" ]; then
    echo "TARGET_EXISTS: $TARGET" >&2
    echo "Use --replace only after preserving the existing installation." >&2
    exit 1
  fi
  stamp="$(date +%Y%m%d-%H%M%S)"
  backup="$HOME/reelforge-agent-next-backup-$stamp"
  if [ -e "$backup" ]; then
    echo "BACKUP_COLLISION: $backup" >&2
    exit 1
  fi
  cp -a "$TARGET" "$backup"
  echo "BACKUP_CREATED=$backup"
else
  mkdir -p "$TARGET"
fi

# Source/config/tests are replaced from the archive.
# The shared MCP/Core/Bridge/TNNL stack is external to the Agent Next package
# and is never created, replaced, or copied by this installer.
rm -rf "$TARGET/app" "$TARGET/config" "$TARGET/tests"
cp -a "$SCRIPT_DIR/app" "$TARGET/app"
cp -a "$SCRIPT_DIR/config" "$TARGET/config"
cp -a "$SCRIPT_DIR/tests" "$TARGET/tests"

# Install the deterministic Agent Next command/verification entrypoints.
cp -a "$SCRIPT_DIR/agent.py" "$TARGET/agent.py"
cp -a "$SCRIPT_DIR/verify.sh" "$TARGET/verify.sh"

# Replace only the bootstrap registry in state; keep durable runtime databases
# and other local state owned by the installed Agent Next.
mkdir -p "$TARGET/state"
cp -a "$SCRIPT_DIR/state/capability_registry.json" "$TARGET/state/capability_registry.json"

for f in ARCHIVE_MANIFEST.md INSTALL.md INSTALL.sh; do
  cp -a "$SCRIPT_DIR/$f" "$TARGET/$f"
done

# Ensure source trees contain no generated bytecode from the packaging workspace.
find "$TARGET/app" "$TARGET/tests" -type d -name __pycache__ -prune -exec rm -rf {} + 2>/dev/null || true
find "$TARGET/app" "$TARGET/tests" -type f -name '*.pyc' -delete 2>/dev/null || true

printf '%s\n' "INSTALL_OK=$TARGET"
if [ -d "$TARGET/ops" ]; then
  printf '%s\n' "OPS_STACK_PRESERVED=$TARGET/ops"
else
  printf '%s\n' "OPS_STACK_PRESERVED=EXTERNAL"
fi
printf '%s\n' "RUNTIME_STATE_PRESERVED=$TARGET/state"
